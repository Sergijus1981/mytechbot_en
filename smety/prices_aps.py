def get_montage_price(name):
    """Возвращает расценку монтажа по названию."""
    if not name:
        return None
    n = name.lower()
    # нормализация: убираем "пожарный", "охранный"
    n = n.replace("пожарный", "").replace("охранный", "").strip()
    n = " ".join(n.split())
    for key, price in MONTAGE_APS.items():
        if key in n:
            return price
    # fallback: по отдельным словам
    words = set(n.split())
    for key, price in MONTAGE_APS.items():
        key_words = set(key.split())
        if key_words and key_words.issubset(words):
            return price
    return None


def get_pnr_price(name):
    """Возвращает расценку ПНР."""
    if not name:
        return None
    n = name.lower()
    for key, price in PNR_APS.items():
        if key in n:
            return price
    return None


def get_cable_price(way):
    """Возвращает расценку кабеля по способу прокладки."""
    if not way:
        return 80  # default
    w = way.lower()
    for key, price in CABLE_APS.items():
        if key in w:
            return price
    return 80


